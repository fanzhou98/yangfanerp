const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const context={document:{addEventListener(){}},window:{addEventListener(){}},console,structuredClone,data:{orders:[]}};
vm.createContext(context);
vm.runInContext(fs.readFileSync('web/forms.js','utf8')+'\n'+fs.readFileSync('web/sheets.js','utf8')+'\nthis.helpers={parseSheetPaste,roundedCents,sourceNet,workingOrder,orderDirty};',context);
const {parseSheetPaste,roundedCents,sourceNet}=context.helpers;
assert.deepEqual(JSON.parse(JSON.stringify(parseSheetPaste('4\t0\t2\r\n2\t\t1\r\n'))),[['4','0','2'],['2','','1']]);
assert.equal(roundedCents('201','3.333'),66993);
assert.equal(roundedCents('1.005','1'),101);
assert.equal(roundedCents('79','3.6')+roundedCents('40','6.2')+roundedCents('3','75'),75740);
assert.equal(roundedCents('not-a-number','3.6'),null);
assert.equal(sourceNet({customer:[{gross:'0.3',count:'1',tare:'0.1'},{gross:'0.2',count:'1',tare:'0.1'}]},'customer'),0.3);
assert.equal(sourceNet({customer:[{gross:'',count:'4',tare:'1.8'}]},'customer'),null);
const o={id:'O1',version:1,customer_id:'C1',business_date:'2026-10-18',batch:'夜间',note:'原单',lines:[{product_id:'P1',ordered_qty:'2',actual_qty:'2',price:'3.6',driver:[],customer:[]}]};
context.data.orders=[o];
const initial=context.helpers.workingOrder(o);
assert.equal(context.helpers.orderDirty(initial),false);
context.data.orders=[{...o,version:2,note:'新版本'}];
const fresh=context.helpers.workingOrder(context.data.orders[0]);
assert.equal(fresh.note,'新版本');assert.equal(context.helpers.orderDirty(fresh),false);
fresh.lines[0].price='5';
context.data.orders=[{...o,version:3,note:'再次变化'}];
